using System;
using System.Collections.Generic;
using System.Linq;
using Raiz;

public static class CareTests {
    static bool Reject(Action action){try{action();return false;}catch(ApiException){return true;}}
    public static void Run(Action<bool,string> check) {
        var now=new DateTime(2026,10,29,16,0,0,DateTimeKind.Utc);
        var c=new Calibration{Dry=392,Wet=281,Dark=22,Bright=316};
        var p=new Plant{Name="Jade",Scientific="Crassula ovata",Watering="Pouca rega"};
        var w=new Weather{FetchedUtc=now,ModelUtc=now,IsDay=true,Temperature=20,Humidity=85};
        var history=Enumerable.Range(0,31).Select(i=>new Sample{Soil=392,Light=260,Utc=now.AddSeconds(i-30)}).ToList();
        var s=history.Last();var r=CareEngine.Evaluate(p,s,w,c,history,now);
        check(r.CanStartWatering,"jade seca por 30s habilita indicacao de rega");
        check(r.Water.Title.Contains("30 mL")&&!r.EstimatedMl.HasValue,"sem tamanho nem historico sugere so porcao experimental, nao total");
        check(r.Soil.Body.Contains("Confirme")&&r.Soil.Body.Contains("ajustável"),"aviso requer verificar substrato e declara gatilho local");
        check(!r.Light.Title.Contains("adequada pela"),"nao afirma luz adequada apenas pelo percentual LDR");
        check(!CareEngine.IsJade(new Plant{Name="jade",Scientific="outra especie"}),"nao aplica perfil jade por nome comum ambiguo");
        var imported=Json.Read<Plant>("{\"Name\":\"Jade\",\"Scientific\":\"Crassula ovata\",\"ApiId\":2193}");
        check(imported.Care!=null&&imported.Care.NearDryIndex==10,"perfil antigo migra com plano de cuidados sem perder especie");
        var wet=new Sample{Soil=281,Light=260,Utc=now};
        r=CareEngine.Evaluate(p,wet,w,c,history,now);
        check(r.Soil.Title.Contains("não precisa regar")&&r.EstimatedMl==null&&!r.CanStartWatering,"referencia umida nunca recomenda mais agua");
        check(r.Water.Title=="Água agora: 0 mL","com solo umido mostra zero mL agora");
        var custom=new Plant{Name="Faixa manual",Soil=new Raiz.Range(30,70)};
        check(CareEngine.Evaluate(custom,wet,w,c,history,now).Soil.Severity=="attention","preserva aviso de solo acima de faixa manual ja cadastrada");
        r=CareEngine.Evaluate(p,new Sample{Soil=335,Light=260,Utc=now},w,c,history,now);
        check(r.Soil.Title=="Umidade adequada para aguardar","secagem intermediaria da jade nao e confundida com necessidade de manter 100%");
        var noisy=history.ToList();noisy[15]=new Sample{Soil=281,Light=260,Utc=now.AddSeconds(-15)};
        check(!CareEngine.Evaluate(p,s,w,c,noisy,now).CanStartWatering,"um pico seco apos leitura umida nao basta");
        check(!CareEngine.Evaluate(p,s,w,c,new List<Sample>{s},now).CanStartWatering,"uma unica amostra nao habilita rega");
        check(!CareEngine.Evaluate(p,s,w,c,history.Where(x=>x.Utc<now.AddSeconds(-20)||x.Utc>now.AddSeconds(-5)).ToList(),now).CanStartWatering,"interrupcao da conexao reinicia persistencia");
        check(!CareEngine.Evaluate(p,s,w,c,history,now.AddSeconds(12)).CanStartWatering,"sensor antigo nao recomenda agua");
        var invalid=new Sample{Soil=1023,Light=260,Utc=now};
        check(!CareEngine.Evaluate(p,invalid,w,c,history,now).HasLiveSoil,"possivel fio solto fora das referencias suspende recomendacao");
        check(!CareEngine.Evaluate(p,s,w,new Calibration(),history,now).CanStartWatering,"sem calibracao nao recomenda agua");
        check(Reject(()=>CareEngine.Start(p,wet,w,c,history,now)),"nao inicia sessao com solo umido");
        CareEngine.Start(p,s,w,c,history,now);
        check(p.Care.Session!=null&&p.Care.Session.InitialIndex==0,"sessao guarda ponto inicial e calibracao");
        CareEngine.AddPortion(p,30,now);CareEngine.AddPortion(p,45,now);
        check(p.Care.Session.TotalMl==75,"registra volumes reais informados sem exigir tamanho do vaso");
        check(Reject(()=>CareEngine.AddPortion(p,0,now))&&Reject(()=>CareEngine.AddPortion(p,-30,now)),"rejeita porcao zero ou negativa");
        check(Reject(()=>CareEngine.Finish(p,wet,c,false,now)),"sem drenagem confirmada nao aprende dose");
        check(Reject(()=>CareEngine.Finish(p,s,c,true,now)),"sem resposta do sensor nao aprende dose");
        check(CareEngine.Evaluate(p,wet,w,c,history,now).Soil.Title.Contains("pause"),"sensor umido durante rega pede pausa em vez de adicionar mais");
        var record=CareEngine.Finish(p,wet,c,true,now);
        check(record.TotalMl==75&&p.Care.Session==null,"finaliza sessao com volume observado e drenagem");
        check(CareEngine.Estimate(p,c)==75,"proxima dose estimada vem do proprio vaso");
        check(!CareEngine.Evaluate(p,s,w,c,history,now).CanStartWatering,"pausa de redistribuicao impede nova rega imediata");
        var next=now.AddDays(5);var nextHistory=history.Select(x=>new Sample{Soil=x.Soil,Light=x.Light,Utc=x.Utc.AddDays(5)}).ToList();
        r=CareEngine.Evaluate(p,nextHistory.Last(),null,c,nextHistory,next);
        check(r.CanStartWatering&&r.EstimatedMl==75,"solo funciona sem internet e usa aprendizado local");
        check(CareEngine.Estimate(p,new Calibration{Dry=500,Wet=200})==null,"troca de calibracao invalida dose aprendida");
        p.Care.Waterings.Add(new WateringRecord{TotalMl=900,DrainageConfirmed=false,Dry=392,Wet=281,InitialIndex=0,FinalIndex=100,FinishedUtc=now});
        check(CareEngine.Estimate(p,c)==75,"sessao sem drenagem nao contamina estimativa");
        p.Care.Waterings.Add(new WateringRecord{TotalMl=100,DrainageConfirmed=true,Dry=392,Wet=281,InitialIndex=0,FinalIndex=100,FinishedUtc=now.AddSeconds(1)});
        p.Care.Waterings.Add(new WateringRecord{TotalMl=3000,DrainageConfirmed=true,Dry=392,Wet=281,InitialIndex=0,FinalIndex=100,FinishedUtc=now.AddSeconds(2)});
        check(CareEngine.Estimate(p,c)==100,"mediana reduz efeito de uma dose discrepante");
        p.Care.LearningResetUtc=now.AddSeconds(3);
        check(CareEngine.Estimate(p,c)==null&&p.Care.Waterings.Count==4,"reiniciar aprendizado preserva registros anteriores");
        CareEngine.Start(p,nextHistory.Last(),null,c,nextHistory,next);CareEngine.AddPortion(p,30,next);CareEngine.Cancel(p,next);
        check(p.Care.Session==null&&p.Care.Waterings.Last().TotalMl==30&&!p.Care.Waterings.Last().DrainageConfirmed,"encerrar sem aprender preserva agua ja informada");
        check(!CareEngine.Evaluate(p,nextHistory.Last(),null,c,nextHistory,next).CanStartWatering,"encerrar sessao com agua tambem pausa nova rega");
        check(Reject(()=>CareEngine.RegisterLight(p,s,w,c,"",now)),"referencia de luz exige descricao");
        CareEngine.RegisterLight(p,s,w,c,"Janela clara confirmada",now);
        r=CareEngine.Evaluate(p,s,w,c,history,now);
        check(r.Light.Title=="Iluminação adequada pela referência","luz adequada e explicitamente relativa ao ponto validado");
        check(r.Light.Body.Contains("20%")&&r.Light.Body.Contains("não comprova"),"luz informa tolerancia local e limite da conclusao");
        var darkHistory=Enumerable.Range(0,61).Select(i=>new Sample{Soil=281,Light=25,Utc=now.AddSeconds(i-60)}).ToList();
        r=CareEngine.Evaluate(p,darkHistory.Last(),w,c,darkHistory,now);
        check(r.Light.Title=="Iluminação abaixo da referência","pouca luz persistente alerta");
        check(CareEngine.Evaluate(p,darkHistory.Last(),w,c,new List<Sample>{darkHistory.Last()},now).Light.Severity=="pending","sombra passageira nao gera alerta");
        w.IsDay=false;
        check(CareEngine.Evaluate(p,darkHistory.Last(),w,c,darkHistory,now).Light.Title=="Luz: pausa noturna","nao classifica noite como luz inadequada");
        check(Reject(()=>CareEngine.RegisterLight(p,s,w,c,"Janela",now)),"nao grava referencia solar durante noite");
        w.IsDay=true;
        check(CareEngine.Evaluate(p,s,w,new Calibration{Dry=392,Wet=281,Dark=10,Bright=500},history,now).Light.Title=="Luz: renove a referência","recalibrar LDR exige renovar ponto iluminado");
        check(CareEngine.Evaluate(p,s,null,c,history,now).Light.Severity=="pending","clima ausente nao inventa contexto diurno");
        var restored=Json.Read<Plant>(Json.Write(p));
        check(restored.ApiId==p.ApiId&&restored.Care.Waterings.Count==p.Care.Waterings.Count&&restored.Care.LightReferenceRaw==260,"planta, aprendizado e referencia sobrevivem a reinicio");
        var q=new Plant{Name="Outra jade",Scientific="Crassula ovata"};
        check(CareEngine.Estimate(q,c)==null&&q.Care.LightReferenceRaw==null,"aprendizado e luz nao vazam para outro vaso");
    }
}
